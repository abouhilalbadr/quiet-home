    // Static warm gradient, drawn once by the window: no extra view, no animation.
    private Drawable background() {
        GradientDrawable base = new GradientDrawable(GradientDrawable.Orientation.TOP_BOTTOM,
                new int[] {0xFF15100F, 0xFF0A0809, 0xFF050405});
        GradientDrawable warm = radial(0x36FF8048, 0.08f, -0.12f, px(1250));
        GradientDrawable plum = radial(0x2EAA3C8C, 1.0f, 1.1f, px(1000));
        for (GradientDrawable g : new GradientDrawable[] {base, warm, plum}) g.setDither(true);
        return new LayerDrawable(new Drawable[] {base, warm, plum});
    }

    // "backgrounds" in settings.conf: all (every picture in the folder, by name), none (the gradient), or
    // file names in the order to show them. Names that aren't in the folder are skipped.
    private String[] backgroundList() {
        List<String> files = new ArrayList<>();
        try {
            String[] found = getAssets().list("bg");
            if (found != null) for (String f : found)
                if (f.toLowerCase(java.util.Locale.ROOT).matches(".*\\.(jpe?g|png|webp)")) files.add(f);
        } catch (Exception ignored) {}
        Collections.sort(files);
        List<String> want = conf.list("backgrounds", "all", false);
        List<String> out = new ArrayList<>();
        if (want.size() == 1 && want.get(0).equalsIgnoreCase("none")) return new String[0];
        if (want.isEmpty() || (want.size() == 1 && want.get(0).equalsIgnoreCase("all"))) want = files;
        for (String f : want) if (files.contains(f)) out.add("bg/" + f);
        return out.toArray(new String[0]);
    }

    // Today's picture: the day number (unless background_change is fixed), moved on by however many
    // times the Background tile was pressed.
    private int backgroundIndex() {
        long now = System.currentTimeMillis();
        long day = (now + java.util.TimeZone.getDefault().getOffset(now)) / 86400000L;
        if (conf.get("background_change", "daily").equalsIgnoreCase("fixed")) day = 0;
        int skips = getSharedPreferences(PREFS, 0).getInt("bg_skips", 0);
        return (int) ((day + skips) % backgrounds.length);
    }

    // Decodes a picture only when it changes, so only one is ever held. Falls back to the gradient.
    private void refreshBackground() {
        if (backgrounds.length == 0) {
            if (shownBackground != -1) getWindow().setBackgroundDrawable(background());
            shownBackground = -1;
            return;
        }
        int i = backgroundIndex();
        if (i == shownBackground) return;
        Drawable d = null;
        try (java.io.InputStream in = getAssets().open(backgrounds[i])) {
            Bitmap b = BitmapFactory.decodeStream(in);
            if (b != null) d = new BitmapDrawable(getResources(), b);
        } catch (Exception ignored) {}
        getWindow().setBackgroundDrawable(d != null ? d : background());
        shownBackground = d != null ? i : -1;
    }

    // Custom tile art in assets/tiles/<package>.png takes the place of that app's own banner.
    private Drawable customTile(String pkg) {
        try (java.io.InputStream in = getAssets().open("tiles/" + pkg + ".png")) {
            Bitmap b = BitmapFactory.decodeStream(in);
            return b == null ? null : new BitmapDrawable(getResources(), b);
        } catch (Exception e) {
            return null;
        }
    }

    private void nextBackground() {
        SharedPreferences prefs = getSharedPreferences(PREFS, 0);
        prefs.edit().putInt("bg_skips", (prefs.getInt("bg_skips", 0) + 1) % Math.max(1, backgrounds.length)).apply();
        refreshBackground();
    }

    private static GradientDrawable radial(int color, float cx, float cy, float r) {
        GradientDrawable g = new GradientDrawable();
        g.setGradientType(GradientDrawable.RADIAL_GRADIENT);
        g.setColors(new int[] {color, color & 0x00FFFFFF});
        g.setGradientCenter(cx, cy);
        g.setGradientRadius(r);
        return g;
    }

    private void buildTiles() {
        // While tiles are swapped out, removing the focused one would hand focus down the row (and
        // overwrite focusedKey), so hold focus off until the new tiles are in.
        String want = focusedKey;
        root.setDescendantFocusability(ViewGroup.FOCUS_BLOCK_DESCENDANTS);
        for (View t : tiles) {
            View wrap = (View) t.getParent();
            ((ViewGroup) wrap.getParent()).removeView(wrap);
        }
        tiles.clear();
        rowApps.clear();
        movingKey = null;
        moveHint.setVisibility(View.GONE);

        PackageManager pm = getPackageManager();
        int m = px(MARGIN), g = px(GAP);
        int w = (getResources().getDisplayMetrics().widthPixels - 2 * m - g * (perRow - 1)) / perRow;
        int h = w * 9 / 16;
        tileW = w;
        tileH = h;

        List<String> apps = appList(pm);
        // All apps share one row; past the edge the row slides. The bottom row keeps its place at the
        // foot of the screen, so bigger tiles grow upward and keep room for the name under the apps.
        int bottomTop = px(GRID_BOTTOM) - h;
        gridTop = bottomTop - h - px(NAME_ROOM);
        ((FrameLayout.LayoutParams) moveHint.getLayoutParams()).topMargin = gridTop - px(64);
        FrameLayout.LayoutParams sp = (FrameLayout.LayoutParams) appScroller.getLayoutParams();
        sp.topMargin = gridTop - px(ROW_LIFT);
        sp.height = px(ROW_LIFT) + h + px(80); // the lift, the tile and the name under it
        appScroller.setLayoutParams(sp);
        root.setMinimumHeight(bottomTop + h + px(MARGIN));

        for (String pkg : apps) {
            Intent li = launchIntent(pm, pkg);
            if (li == null) continue;
            Drawable banner = customTile(pkg);
            if (banner == null) try {
                banner = pm.getActivityBanner(li);
                if (banner == null) banner = pm.getApplicationBanner(pkg);
            } catch (Exception ignored) {}
            String label = pkg;
            try { label = pm.getApplicationLabel(pm.getApplicationInfo(pkg, 0)).toString(); } catch (Exception ignored) {}
            // Apps without a TV banner get a plain tile with their normal icon.
            Drawable icon = null;
            if (banner == null) try { icon = pm.getApplicationIcon(pkg); } catch (Exception ignored) {}
            int i = rowApps.size();
            rowApps.add(pkg);
            addTile(appRow, pkg, label, banner, null, icon, gridX(i), gridY(i), w, h);
        }
        // Right on the last app stays put, instead of jumping up to the network icon.
        if (!rowApps.isEmpty()) {
            View last = tile(rowApps.get(rowApps.size() - 1));
            last.setId(View.generateViewId());
            last.setNextFocusRightId(last.getId());
        }

        // Bottom row, in the order "bottom_row" in settings.conf lists them, one row at most: play_store,
        // inputs (the TV's HDMI inputs, as many as fit), settings, background and add_app. Play Store is
        // left out when it's already a top-row app, and Background when there are no pictures.
        List<String> bottom = new ArrayList<>(conf.list("bottom_row", DEFAULT_BOTTOM_ROW, true));
        if (apps.contains(PLAY_STORE) || launchIntent(pm, PLAY_STORE) == null) bottom.remove("play_store");
        if (backgrounds.length == 0) bottom.remove("background");
        List<TvInputInfo> inputs = bottom.contains("inputs") ? hdmiInputs() : new ArrayList<TvInputInfo>();
        int room = perRow - (bottom.size() - (bottom.contains("inputs") ? 1 : 0));
        if (inputs.size() > Math.max(0, room)) inputs = inputs.subList(0, Math.max(0, room));
        int col = 0;
        for (String item : bottom) {
            if (item.equals("inputs")) {
                for (TvInputInfo in : inputs)
                    addTile(root, in.getId(), inputLabel(in), null, LineIcon.HDMI, null, m + col++ * (w + g), bottomTop, w, h);
                continue;
            }
            if (col >= perRow) break;
            int x = m + col * (w + g);
            switch (item) {
                case "play_store": addTile(root, PLAY_STORE, "Play Store", null, LineIcon.PLAY, null, x, bottomTop, w, h); break;
                case "settings": addTile(root, SETTINGS, "Settings", null, LineIcon.SETTINGS, null, x, bottomTop, w, h); break;
                case "background": addTile(root, BACKGROUND, "Background", null, LineIcon.IMAGE, null, x, bottomTop, w, h); break;
                case "add_app": addTile(root, ADD, "Add app", null, LineIcon.PLUS, null, x, bottomTop, w, h); break;
                default: continue; // a name this version doesn't know
            }
            col++;
        }

        // Plain icons at the top right, level with the date: any settings shortcuts picked, then the
        // network icon ("network_icon" in settings.conf). Added last, so the first app keeps first focus;
        // Up from the apps reaches them.
        List<Integer> quick = quickList();
        boolean net = conf.yes("network_icon", true);
        int n = quick.size() + (net ? 1 : 0);
        int ib = px(ICON_BUTTON), ig = px(ICON_GAP);
        // The last icon's right edge lines up with the apps' (its focus circle sticks out past them).
        int qx = getResources().getDisplayMetrics().widthPixels - m + (ib - px(ICON_SIZE)) / 2
                - n * ib - Math.max(0, n - 1) * ig;
        for (int q : quick) {
            addIcon(QUICK + QUICK_NAMES[q], QUICK_LABELS[q], new LineIcon(QUICK_ICONS[q]), qx);
            qx += ib + ig;
        }
        netIcon = net ? addIcon(NETWORK, "Network", null, qx) : null;
        netState = -1;
        refreshNetwork();

        root.setDescendantFocusability(ViewGroup.FOCUS_AFTER_DESCENDANTS);
        View restore = null;
        for (View t : tiles) if (t.getTag().equals(want)) restore = t;
        if (restore != null) restore.requestFocus();
    }

    private void addTile(ViewGroup parent, final String key, String label, Drawable banner, int[] lineIcon, Drawable appIcon,
                         int x, int y, int w, int h) {
        FrameLayout card = new FrameLayout(this);
        // Icons and names grow with the tile; six per row is the design size.
        final float grow = 6f / perRow;
        final GradientDrawable bg = new GradientDrawable();
        bg.setCornerRadius(px(RADIUS));
        if (banner != null) {
            bg.setColor(0xFF1E1A1C);
            ImageView iv = new ImageView(this);
            iv.setImageDrawable(fit(banner, w, h));
            card.addView(iv, new FrameLayout.LayoutParams(-1, -1));
        } else {
            // Quiet "glass" tile: icon above label.
            bg.setColor(0x13FFFFFF);
            bg.setStroke(Math.max(1, px(2)), 0x17FFFFFF);
            LinearLayout inner = new LinearLayout(this);
            inner.setOrientation(LinearLayout.VERTICAL);
            inner.setGravity(Gravity.CENTER);
            ImageView iv = new ImageView(this);
            int size = Math.round((lineIcon != null ? px(44) : px(64)) * grow);
            if (lineIcon != null) iv.setImageDrawable(new LineIcon(lineIcon));
            else if (appIcon != null) iv.setImageDrawable(fit(appIcon, size, size));
            inner.addView(iv, new LinearLayout.LayoutParams(size, size));
            TextView t = text(Math.round(px(24) * grow), 0xE0FFFFFF, regular);
            t.setText(label);
            t.setSingleLine(true);
            t.setEllipsize(android.text.TextUtils.TruncateAt.END);
            t.setGravity(Gravity.CENTER);
            t.setPadding(px(16), 0, px(16), 0);
            LinearLayout.LayoutParams lp = new LinearLayout.LayoutParams(-2, -2);
            lp.topMargin = Math.round(px(12) * grow);
            inner.addView(t, lp);
            card.addView(inner, new FrameLayout.LayoutParams(-1, -1));
        }
        card.setBackground(bg);
        card.setClipToOutline(true);
        card.setFocusable(true);
        card.setTag(key);

        // Banner tiles show their name underneath when focused.
        final TextView caption = banner == null ? null : text(Math.round(px(24) * grow), Color.WHITE, regular);
        if (caption != null) {
            caption.setText(label);
            caption.setGravity(Gravity.CENTER_HORIZONTAL);
            caption.setVisibility(View.INVISIBLE);
        }

        final boolean glass = banner == null;
        card.setOnFocusChangeListener((v, has) -> {
            if (has) focusedKey = key;
            if (glass) bg.setColor(has ? focusGlass() : 0x13FFFFFF);
            v.animate().scaleX(has ? 1.1f : 1f).scaleY(has ? 1.1f : 1f).translationZ(has ? px(26) : 0)
                    .setDuration(140).withLayer().start();
            if (caption != null) caption.setVisibility(has ? View.VISIBLE : View.INVISIBLE);
        });
        final boolean editable = rowApps.contains(key);
        card.setOnClickListener(v -> open(key));
        if (editable) card.setOnLongClickListener(v -> { showEditMenu(key); return true; });
        card.setOnKeyListener((v, code, ev) -> {
            boolean ok = code == KeyEvent.KEYCODE_DPAD_CENTER || code == KeyEvent.KEYCODE_ENTER
                    || code == KeyEvent.KEYCODE_NUMPAD_ENTER;
            boolean down = ev.getAction() == KeyEvent.ACTION_DOWN;
            if (key.equals(movingKey)) return moveKey(key, code, ok, down);
            if (editable && code == KeyEvent.KEYCODE_MENU) {
                if (!down) showEditMenu(key);
                return true;
            }
            if (!ok) return false;
            if (down) {
                if (ev.getRepeatCount() == 0) longPressed = false;
                else if (editable && !longPressed && (ev.isLongPress()
                        || ev.getEventTime() - ev.getDownTime() >= ViewConfiguration.getLongPressTimeout())) {
                    longPressed = true;
                    showEditMenu(key);
                }
            } else if (!longPressed) {
                open(key);
            }
            return true;
        });

        FrameLayout wrap = new FrameLayout(this);
        wrap.setClipChildren(false);
        wrap.addView(card, new FrameLayout.LayoutParams(w, h));
        if (caption != null) {
            FrameLayout.LayoutParams cp = new FrameLayout.LayoutParams(w, -2);
            cp.topMargin = h + px(22);
            wrap.addView(caption, cp);
        }
        parent.addView(wrap, at(x, y, w, -2));
        tiles.add(card);
    }


    @Override
    protected void onNewIntent(Intent intent) {
        super.onNewIntent(intent);
        setIntent(intent);
        if (saveConfig(intent)) buildTiles();
    }

    // Saves an app list passed with --es apps "..." and shortcuts passed with --es quick "...".
    // Returns true if it changed.
    // When Android kills the home screen in the background, it can start it again with the same old
    // intent; the stamp install.sh sends stops that from undoing changes made on the TV since.
    private boolean saveConfig(Intent intent) {
        String apps = intent == null ? null : intent.getStringExtra("apps");
        String quick = intent == null ? null : intent.getStringExtra("quick");
        if (apps == null && quick == null) return false;
        SharedPreferences prefs = getSharedPreferences(PREFS, 0);
        String stamp = intent.getStringExtra("stamp");
        if (stamp != null && stamp.equals(prefs.getString("stamp", null))) return false;
        SharedPreferences.Editor e = prefs.edit();
        if (stamp != null) e.putString("stamp", stamp);
        if (apps != null) {
            apps = apps.trim();
            if (apps.isEmpty() || apps.equalsIgnoreCase("auto")) e.remove("apps");
            else e.putString("apps", apps).putString("apps_from", confApps());
        }
        if (quick != null) {
            quick = quick.trim();
            // "none" is saved too, so it also hides the shortcuts settings.conf asks for.
            e.putString("quick", quick.isEmpty() ? "none" : quick).putString("quick_from", confQuick());
        }
        e.apply();
        dirty = true;
        return true;
    }

    // The "apps" and "shortcuts" lines this build came with. A list saved on the TV remembers which build
    // it was made on, and gives way when a new build changes that line.
    private String confApps() { return android.text.TextUtils.join(",", conf.list("apps", DEFAULT_APPS, false)); }
    private String confQuick() { return android.text.TextUtils.join(",", conf.list("shortcuts", "", true)); }

    // The saved value of key, unless settings.conf's line has changed since it was saved; then it's dropped.
    private String savedUnlessRebuilt(String key, String fromKey, String fromConf) {
        SharedPreferences prefs = getSharedPreferences(PREFS, 0);
        String saved = prefs.getString(key, null);
        if (saved != null && !fromConf.equals(prefs.getString(fromKey, fromConf))) {
            prefs.edit().remove(key).remove(fromKey).apply();
            return null;
        }
        return saved;
    }

    private List<String> appList(PackageManager pm) {
        List<String> out = new ArrayList<>();
        String saved = savedUnlessRebuilt("apps", "apps_from", confApps());
        List<String> wanted = saved != null ? Arrays.asList(saved.split("[,\\s]+")) : conf.list("apps", DEFAULT_APPS, false);
        for (String p : wanted) if (!p.isEmpty() && !out.contains(p) && launchIntent(pm, p) != null) out.add(p);
        if (saved == null && conf.yes("add_other_apps", true)) {
            // Top up with other TV apps people installed (or updated), skipping launchers and system tools.
            Intent q = new Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_LEANBACK_LAUNCHER);
            for (ResolveInfo ri : pm.queryIntentActivities(q, 0)) {
                if (out.size() >= perRow) break;
                String p = ri.activityInfo.packageName;
                int flags = ri.activityInfo.applicationInfo.flags;
                boolean stockSystem = (flags & ApplicationInfo.FLAG_SYSTEM) != 0
                        && (flags & ApplicationInfo.FLAG_UPDATED_SYSTEM_APP) == 0;
                if (stockSystem || out.contains(p) || NOT_APPS.contains(p) || p.equals(getPackageName())) continue;
                out.add(p);
            }
        }
        return out;
    }

    @Override
    protected void onResume() {
        super.onResume();
        // Rebuild only when apps were installed, removed or updated.
        if (dirty) {
            dirty = false;
            buildTiles();
        }
        refreshNetwork();
        refreshBackground(); // a new day brings the next picture
        View f = getCurrentFocus();
        if (f == null && !tiles.isEmpty()) tiles.get(0).requestFocus();
    }

